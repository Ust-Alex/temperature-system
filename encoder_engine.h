#ifndef ENCODER_ENGINE_H
#define ENCODER_ENGINE_H

#include <Arduino.h>

// ============================================================================
// ТИПЫ СОБЫТИЙ ЭНКОДЕРА (РАСШИРЕННЫЕ)
// ============================================================================
typedef enum {
    EVENT_NONE,                 // Нет события
    
    // События кнопки
    EVENT_BUTTON_CLICK,         // Короткое нажатие (одиночный клик)
    EVENT_BUTTON_DOUBLE,        // Двойное нажатие
    EVENT_BUTTON_HOLD,          // Начало удержания кнопки (без поворота)
    
    // Поворот с удержанием (для изменения параметров)
    EVENT_HOLD_LEFT,            // Поворот влево с удержанием кнопки
    EVENT_HOLD_RIGHT,           // Поворот вправо с удержанием кнопки
    
    // Обычный поворот (без удержания)
    EVENT_ENCODER_LEFT,         // Поворот влево
    EVENT_ENCODER_RIGHT         // Поворот вправо
    
} EncoderEvent_t;

// ============================================================================
// ФУНКЦИИ УПРАВЛЕНИЯ ЭНКОДЕРОМ
// ============================================================================

/**
 * @brief Инициализация энкодера
 * @details Настраивает пины, таймауты и режимы работы библиотеки EncButton
 */
void encoder_init();

/**
 * @brief Опрос энкодера (вызывать каждые 10-20 мс)
 * @return EncoderEvent_t - тип произошедшего события
 * @details Должна вызываться из задачи taskEncoder с высокой частотой
 */
EncoderEvent_t encoder_tick();

/**
 * @brief Сброс таймера неактивности
 * @details Вызывается при любом действии пользователя
 */
void encoder_reset_inactivity_timer();

/**
 * @brief Получение времени неактивности пользователя
 * @return uint32_t - время в миллисекундах с последнего действия
 */
uint32_t encoder_get_inactivity_time();

#endif // ENCODER_ENGINE_H