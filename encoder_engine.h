#ifndef ENCODER_ENGINE_H
#define ENCODER_ENGINE_H

#include <Arduino.h>

// ============================================================================
// ТИПЫ СОБЫТИЙ ЭНКОДЕРА
// ============================================================================

typedef enum {
    EVENT_NONE,                 /**< Нет события */
    
    // События кнопки
    EVENT_BUTTON_CLICK,         /**< Короткое нажатие (одиночный клик) */
    EVENT_BUTTON_DOUBLE,        /**< Двойное нажатие */
    EVENT_BUTTON_HOLD,          /**< Начало удержания кнопки (без поворота) */
    
    // Поворот с удержанием
    EVENT_HOLD_LEFT,            /**< Поворот влево с удержанием кнопки */
    EVENT_HOLD_RIGHT,           /**< Поворот вправо с удержанием кнопки */
    
    // Обычный поворот (без удержания)
    EVENT_ENCODER_LEFT,         /**< Поворот влево */
    EVENT_ENCODER_RIGHT         /**< Поворот вправо */
    
} EncoderEvent_t;

// ============================================================================
// ФУНКЦИИ УПРАВЛЕНИЯ ЭНКОДЕРОМ
// ============================================================================

void encoder_init();
void encoder_tick();
void encoder_reset_inactivity_timer();
uint32_t encoder_get_inactivity_time();

#endif // ENCODER_ENGINE_H