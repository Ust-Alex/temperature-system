#ifndef MP3_PLAYER_H
#define MP3_PLAYER_H

#include "system_config.h"

// ============================================================================
// КОНСТАНТЫ КОМАНД (используются в поле cmd структуры Mp3Command_t)
// ============================================================================

#define MP3_CMD_PLAY_TRACK      1  // Воспроизвести трек. Параметр: номер трека (1-65535)
#define MP3_CMD_SET_VOLUME      2  // Установить громкость. Параметр: уровень (0-30)
#define MP3_CMD_STOP            3  // Остановить воспроизведение. Параметр: игнорируется.
#define MP3_CMD_PAUSE           4  // Поставить на паузу. Параметр: игнорируется.
#define MP3_CMD_RESUME          5  // Продолжить с паузы. Параметр: игнорируется.
#define MP3_CMD_PLAY_FOLDER     6  // Воспроизвести трек из папки. Параметр: (папка << 8) | трек
#define MP3_CMD_NEXT            7  // Следующий трек. Параметр: игнорируется.
#define MP3_CMD_PREVIOUS        8  // Предыдущий трек. Параметр: игнорируется.
#define MP3_CMD_PLAY_ADVERT     9  // Воспроизвести рекламный трек. Параметр: номер трека
#define MP3_CMD_ENABLE_REPEAT  10  // Включить повтор: param = интервал в секундах
#define MP3_CMD_DISABLE_REPEAT 11  // Выключить повтор

// ============================================================================
// ПРОТОТИПЫ ФУНКЦИЙ ДЛЯ РАБОТЫ С MP3-ПРОИГРЫВАТЕЛЕМ
// ============================================================================

/**
 * ИНИЦИАЛИЗАЦИЯ DFPLAYER
 * Вызывается один раз в setup() после initHardware()
 * Настраивает аппаратный UART и проверяет наличие плеера
 * 
 * @return true - плеер успешно инициализирован, false - ошибка инициализации
 */
bool initMP3Player();

/**
 * ОСНОВНАЯ ЗАДАЧА MP3-ПРОИГРЫВАТЕЛЯ (FreeRTOS task)
 * Должна быть создана через xTaskCreate() после успешной инициализации
 * Обрабатывает команды из очереди mp3CommandQueue в фоновом режиме
 * 
 * @param pvParameters Не используется (можно передать NULL)
 */
void taskMP3(void* pvParameters);

/**
 * УПРАВЛЯЮЩАЯ ФУНКЦИЯ ДЛЯ ОТПРАВКИ КОМАНД В ОЧЕРЕДЬ
 * Потокобезопасная обертка для отправки команд в задачу MP3
 * Проверяет состояние очереди и готовность плеера
 * 
 * @param command Структура команды для отправки
 * @return true - команда успешно поставлена в очередь, false - ошибка отправки
 */
bool sendMP3Command(Mp3Command_t command);

/**
 * БЫСТРАЯ ПРОВЕРКА - ИДЕТ ЛИ ВОСПРОИЗВЕДЕНИЕ
 * Читает состояние пина BUSY (LOW = воспроизведение, HIGH = остановлено)
 * Не требует инициализации плеера, работает на уровне GPIO
 * 
 * @return true - идет воспроизведение, false - плеер остановлен или на паузе
 */
bool isMP3Playing();

/**
 * ПРОСТОЙ ВРАППЕР ДЛЯ ВОСПРОИЗВЕДЕНИЯ ТРЕКА
 * Упрощенный интерфейс для воспроизведения трека по номеру
 * Автоматически проверяет, не играет ли уже что-то
 * 
 * @param trackNumber Номер трека для воспроизведения (1-65535)
 * @return true - команда отправлена, false - ошибка или плеер уже играет
 */
bool playTrack(uint16_t trackNumber);

/**
 * ПРОСТОЙ ВРАППЕР ДЛЯ УСТАНОВКИ ГРОМКОСТИ
 * Упрощенный интерфейс для настройки громкости
 * 
 * @param volume Уровень громкости (0-30, где 30 - максимальная)
 * @return true - команда отправлена, false - ошибка
 */
bool setVolume(uint8_t volume);

#endif // MP3_PLAYER_H