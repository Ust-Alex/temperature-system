/**
 * ПРИНУДИТЕЛЬНАЯ УСТАНОВКА ДАТЧИКА КАК "НАЙДЕННОГО" (ДЛЯ ТЕСТИРОВАНИЯ)
 * 
 * Назначение: Создать виртуальные датчики для тестирования системы
 *             когда физические датчики отсутствуют или неисправны
 * 
 * Использование: Для отладки интерфейса, тестирования дисплея,
 *                проверки логики системы без аппаратной части
 * 
 * Параметры:
 *   sensorIdx - индекс датчика для эмуляции (0-3)
 *   fakeTemp  - тестовое значение температуры для эмуляции
 */
void forceSensorFound(int sensorIdx, float fakeTemp) {
  // Защита от некорректных индексов
  if (sensorIdx < 0 || sensorIdx >= 4) return;
  
  Serial.printf("\n[ТЕСТ] Принудительная установка датчика %s\n", 
                sensorNames[sensorIdx]);
  
  // 1. Устанавливаем флаг "найден"
  sensors[sensorIdx].found = true;
  
  // 2. Создаём тестовый адрес Dallas (начинается с 0x28)
  sensors[sensorIdx].addr[0] = 0x28;  // Семейство Dallas
  sensors[sensorIdx].addr[1] = 0xAA;  // Произвольные байты
  sensors[sensorIdx].addr[2] = 0xBB;
  sensors[sensorIdx].addr[3] = 0xCC;
  sensors[sensorIdx].addr[4] = 0xDD;
  sensors[sensorIdx].addr[5] = 0xEE;
  sensors[sensorIdx].addr[6] = 0xFF;
  sensors[sensorIdx].addr[7] = 0x10 + sensorIdx;  // Уникальный код
  
  // 3. Устанавливаем тестовую температуру
  sensors[sensorIdx].temp = fakeTemp;
  
  // 4. Сбрасываем счётчик потерь
  sensors[sensorIdx].lostTimer = 0;
  
  // 5. Обновляем системные данные (с защитой мьютексом)
  safeUpdateSystemData(sensorIdx, fakeTemp, 0.0f);
  
  // 6. ОСОБАЯ ОБРАБОТКА ДЛЯ ДАТЧИКА ГИЛЬЗЫ (индекс 3)
  if (sensorIdx == 3) {
    // Датчик гильзы критически важен - обновляем системные флаги
    criticalError = false;
    systemInitialized = true;
    
    Serial.printf("[ТЕСТ] ✅ Датчик гильзы принудительно установлен\n");
    Serial.printf("       📏 Температура: %.1f°C\n", fakeTemp);
    Serial.println("       ⚠️  ВНИМАНИЕ: Режим теста, датчик эмулирован!");
  } else {
    // Для датчиков стенок - просто логируем
    Serial.printf("[ТЕСТ] ✅ %s принудительно установлен\n", 
                  sensorNames[sensorIdx]);
    Serial.printf("       📏 Температура: %.1f°C\n", fakeTemp);
  }
}

