/** * ИНИЦИАЛИЗАЦИЯ СИСТЕМЫ ИЗМЕРЕНИЙ - ГЛАВНАЯ ФУНКЦИЯ МОДУЛЯ
 * 
 * Назначение: Обнаружение, инициализация и настройка всех датчиков температуры
 *             Установка начального состояния системы
 * 
 * Возвращает: true  - система успешно инициализирована (найден датчик гильзы)
 *             false - критическая ошибка (датчик гильзы не обнаружен)
 * 
 * КРИТИЧЕСКОЕ ИСПРАВЛЕНИЕ: Добавлена правильная инициализация цепочки:
 *                         OneWire → DallasTemperature → begin()
 */
bool begin() {
  Serial.println("\n" + String(60, '='));
  Serial.println("🚀 ЗАПУСК ЯДРА ИЗМЕРЕНИЙ (УСИЛЕННАЯ ВЕРСИЯ)");
  Serial.println(String(60, '='));
  
  // -------------------- ЭТАП 1: ПОДГОТОВКА СТРУКТУР ДАННЫХ --------------------
  Serial.println("\n📋 ЭТАП 1: Подготовка структур данных");
  
  // Сброс глобальных флагов состояния системы
  criticalError = false;       // Сбрасываем флаг критической ошибки
  systemInitialized = false;   // Система ещё не инициализирована
  
  // Инициализация массива структур датчиков
  for (int i = 0; i < 4; i++) {
    sensors[i].found = false;           // Датчик пока не найден
    sensors[i].temp = TEMP_NO_DATA;     // Устанавливаем значение "нет данных"
    sensors[i].lostTimer = 0;           // Сбрасываем счётчик потерь
    sensors[i].filterIndex = 0;         // Сброс индекса фильтра
    sensors[i].filterSum = 0.0f;        // Сброс суммы фильтра
    
    // Очистка адреса датчика (8 байт для 1-Wire)
    memset(sensors[i].addr, 0, 8);
    
    // Очистка буфера медианного фильтра (5 значений)
    memset(sensors[i].filterBuffer, 0, sizeof(float) * 5);
  }
  
  Serial.println("✅ Структуры датчиков сброшены и готовы к работе");
  
  // -------------------- ЭТАП 2: ИНИЦИАЛИЗАЦИЯ ШИНЫ A (ГИЛЬЗА) --------------------
  Serial.println("\n" + String(40, '-'));
  Serial.println("🔧 ЭТАП 2: Инициализация шины A (GPIO4 - ДАТЧИК ГИЛЬЗЫ)");
  Serial.println(String(40, '-'));
  
  // ШАГ 2.1: ИНИЦИАЛИЗАЦИЯ ОБЪЕКТА ONEWIRE ДЛЯ ШИНЫ A
  // -----------------------------------------------------------------
  Serial.print("1. Инициализация OneWire на GPIO4... ");
  
  // КРИТИЧЕСКИ ВАЖНО: Сначала создаём объект OneWire для физической шины
  // Это устанавливает связь между библиотекой и конкретным GPIO пином
  oneWireA.begin(ONE_WIRE_BUS_A);  // ONE_WIRE_BUS_A = 4 (GPIO4)
  
  delay(100);  // Задержка для стабилизации шины после подачи питания
  Serial.println("✅");
  
  // ШАГ 2.2: СВЯЗЫВАНИЕ DALLAS TEMPERATURE С ONEWIRE
  // -----------------------------------------------------------------
  Serial.print("2. Связывание DallasTemperature с OneWire... ");
  
  // КРИТИЧЕСКИ ВАЖНО: Нужно явно указать DallasTemperature, какой объект
  // OneWire использовать. Без этого sensorsA будет работать с неправильной шиной!
  sensorsA.setOneWire(&oneWireA);  // Связываем sensorsA с oneWireA
  
  Serial.println("✅");
  
  // ШАГ 2.3: ЗАПУСК БИБЛИОТЕКИ DALLAS TEMPERATURE
  // -----------------------------------------------------------------
  Serial.print("3. Запуск библиотеки DallasTemperature... ");
  
  // Инициализация библиотеки DallasTemperature
  sensorsA.begin();
  
  delay(100);  // Даём время на инициализацию
  Serial.println("✅");
  
  // ШАГ 2.4: ПОИСК УСТРОЙСТВ НА ШИНЕ A
  // -----------------------------------------------------------------
  Serial.print("4. Поиск устройств на шине A... ");
  
  // Запрашиваем количество обнаруженных устройств на шине
  int countA = sensorsA.getDeviceCount();
  Serial.printf("найдено: %d устройств\n", countA);
  
  // ОБРАБОТКА РЕЗУЛЬТАТОВ ПОИСКА НА ШИНЕ A
  if (countA > 0) {
    // УСПЕХ: На шине найдены устройства
    
    // Получаем адрес первого (и единственного) датчика на шине A
    DeviceAddress tempAddr;  // Временная переменная для адреса
    if (sensorsA.getAddress(tempAddr, 0)) {
      // Копируем 8-байтовый адрес в структуру датчика гильзы (индекс 3)
      memcpy(sensors[3].addr, tempAddr, 8);
      
      // КРИТИЧЕСКИ ВАЖНО: Устанавливаем флаг "найден"!
      // Без этого система будет считать датчик потерянным
      sensors[3].found = true;
      
      // Настраиваем разрешение датчика (11 бит = точность 0.125°C)
      sensorsA.setResolution(tempAddr, RESOLUTION);
      
      // Выводим информацию о найденном датчике
      Serial.print("   ✅ ДАТЧИК ГИЛЬЗЫ НАЙДЕН! Адрес: ");
      for (int i = 0; i < 8; i++) {
        Serial.printf("%02X", tempAddr[i]);
        if (i < 7) Serial.print(":");
      }
      Serial.println();
    }
  } else {
    // ОШИБКА: На шине A не обнаружено устройств
    Serial.println("   ❌ НА ШИНЕ A УСТРОЙСТВА НЕ ОБНАРУЖЕНЫ");
    
    // ДЕТАЛЬНАЯ ДИАГНОСТИКА: Проверяем шину напрямую через OneWire
    Serial.println("   🔍 Диагностика шины A:");
    
    // Отправляем reset pulse и проверяем presence pulse
    oneWireA.reset();
    delayMicroseconds(480);  // Ожидаем ответа устройств
    byte presence = oneWireA.read();  // Читаем ответ
    
    Serial.printf("     - Presence pulse: %s\n", 
                  presence == 0 ? "✅ ОБНАРУЖЕН" : "❌ ОТСУТСТВУЕТ");
    
    if (presence != 0) {
      Serial.println("     ⚠️  ВОЗМОЖНЫЕ ПРИЧИНЫ:");
      Serial.println("       1. Датчик не подключён к GPIO4 (пин 29)");
      Serial.println("       2. Отсутствует питание 3.3V на датчике");
      Serial.println("       3. Нет подтягивающего резистора 4.7кОм");
      Serial.println("       4. Датчик подключён к другому GPIO");
      Serial.println("       5. Неисправность датчика или проводов");
    }
  }
  
  // -------------------- ЭТАП 3: ИНИЦИАЛИЗАЦИЯ ШИНЫ B (СТЕНКИ) --------------------
  Serial.println("\n" + String(40, '-'));
  Serial.println("🔧 ЭТАП 3: Инициализация шины B (GPIO16 - ДАТЧИКИ СТЕНОК)");
  Serial.println(String(40, '-'));
  
  // ШАГ 3.1: ИНИЦИАЛИЗАЦИЯ ОБЪЕКТА ONEWIRE ДЛЯ ШИНЫ B
  // -----------------------------------------------------------------
  Serial.print("1. Инициализация OneWire на GPIO16... ");
  
  // Аналогично шине A: создаём объект для второй шины
  oneWireB.begin(ONE_WIRE_BUS_B);  // ONE_WIRE_BUS_B = 16 (GPIO16)
  
  delay(100);
  Serial.println("✅");
  
  // ШАГ 3.2: СВЯЗЫВАНИЕ DALLAS TEMPERATURE С ONEWIRE
  // -----------------------------------------------------------------
  Serial.print("2. Связывание DallasTemperature с OneWire... ");
  
  sensorsB.setOneWire(&oneWireB);  // Связываем sensorsB с oneWireB
  
  Serial.println("✅");
  
  // ШАГ 3.3: ЗАПУСК БИБЛИОТЕКИ DALLAS TEMPERATURE
  // -----------------------------------------------------------------
  Serial.print("3. Запуск библиотеки DallasTemperature... ");
  
  sensorsB.begin();
  
  delay(100);
  Serial.println("✅");
  
  // ШАГ 3.4: ПОИСК УСТРОЙСТВ НА ШИНЕ B
  // -----------------------------------------------------------------
  Serial.print("4. Поиск устройств на шине B... ");
  
  int countB = sensorsB.getDeviceCount();
  Serial.printf("найдено: %d устройств\n", countB);
  
  // ОБРАБОТКА РЕЗУЛЬТАТОВ ПОИСКА НА ШИНЕ B
  if (countB > 0) {
    // УСПЕХ: На шине B найдены устройства (стенки)
    
    // Определяем сколько датчиков реально нужно прочитать
    int devicesToRead = min(countB, 3);  // Максимум 3 датчика стенок
    
    // Массив для временного хранения найденных адресов
    DeviceAddress foundAddrs[3];
    
    Serial.printf("   📊 Чтение адресов %d датчиков...\n", devicesToRead);
    
    for (int i = 0; i < devicesToRead; i++) {
      // Получаем адрес i-го устройства на шине
      if (sensorsB.getAddress(foundAddrs[i], i)) {
        // ПРОСТАЯ СХЕМА РАСПРЕДЕЛЕНИЯ: 
        // Первый найденный → первый датчик (индекс 0)
        // Второй найденный → второй датчик (индекс 1)  
        // Третий найденный → третий датчик (индекс 2)
        int sensorIndex = i;  // 0, 1 или 2
        
        // Копируем адрес в соответствующую структуру датчика
        memcpy(sensors[sensorIndex].addr, foundAddrs[i], 8);
        
        // Устанавливаем флаг "найден" для датчика стенки
        sensors[sensorIndex].found = true;
        
        // Настраиваем разрешение датчика
        sensorsB.setResolution(foundAddrs[i], RESOLUTION);
        
        // Выводим информацию о найденном датчике
        Serial.printf("   ✅ %s найден и инициализирован\n", 
                      sensorNames[sensorIndex]);
      }
    }
  } else {
    // ОШИБКА: На шине B не обнаружено устройств
    Serial.println("   ❌ НА ШИНЕ B УСТРОЙСТВА НЕ ОБНАРУЖЕНЫ");
    
    // Диагностика шины B
    Serial.println("   🔍 Диагностика шины B:");
    
    oneWireB.reset();
    delayMicroseconds(480);
    byte presence = oneWireB.read();
    
    Serial.printf("     - Presence pulse: %s\n",
                  presence == 0 ? "✅ ОБНАРУЖЕН" : "❌ ОТСУТСТВУЕТ");
  }
  
  // -------------------- ЭТАП 4: ФИНАЛЬНАЯ ПРОВЕРКА И УСТАНОВКА ФЛАГОВ --------------------
  Serial.println("\n" + String(50, '-'));
  Serial.println("📊 ЭТАП 4: Финальные результаты инициализации");
  Serial.println(String(50, '-'));
  
  // Подсчитываем сколько датчиков успешно найдено
  int foundCount = 0;
  for (int i = 0; i < 4; i++) {
    if (sensors[i].found) {
      foundCount++;
      Serial.printf("   [%d] %s: ✅ НАЙДЕН\n", i, sensorNames[i]);
    } else {
      Serial.printf("   [%d] %s: ❌ НЕ НАЙДЕН\n", i, sensorNames[i]);
    }
  }
  
  // -------------------- ЭТАП 5: ПРОВЕРКА КРИТИЧЕСКИХ УСЛОВИЙ --------------------
  Serial.println("\n" + String(40, '='));
  Serial.println("⚡ КРИТИЧЕСКАЯ ПРОВЕРКА СИСТЕМЫ");
  Serial.println(String(40, '='));
  
  // КРИТИЧЕСКОЕ УСЛОВИЕ: ДАТЧИК ГИЛЬЗЫ ДОЛЖЕН БЫТЬ НАЙДЕН!
  if (sensors[3].found) {
    // УСПЕХ: Система может работать
    Serial.println("✅ КРИТИЧЕСКИЙ ДАТЧИК (ГИЛЬЗА) НАЙДЕН!");
    
    // Устанавливаем системные флаги в рабочее состояние
    criticalError = false;      // Нет критических ошибок
    systemInitialized = true;   // Система инициализирована и готова
    
    // Устанавливаем базовую температуру гильзы для режима MODE2
    // (значение по умолчанию, если ещё не сохранено пользователем)
    if (guildBaseTemp == 0.0f) {
      guildBaseTemp = 20.0f;  // Температура по умолчанию 20°C
      Serial.printf("   Базовая температура гильзы: %.1f°C (по умолчанию)\n", 
                    guildBaseTemp);
    }
    
    Serial.println("\n🎉 СИСТЕМА УСПЕШНО ИНИЦИАЛИЗИРОВАНА И ГОТОВА К РАБОТЕ!");
  } else {
    // КРИТИЧЕСКАЯ ОШИБКА: Система не может работать без датчика гильзы
    Serial.println("❌ КРИТИЧЕСКАЯ ОШИБКА: ДАТЧИК ГИЛЬЗЫ НЕ НАЙДЕН!");
    
    // Устанавливаем флаги ошибки
    criticalError = true;       // Критическая ошибка!
    systemInitialized = false;  // Система не инициализирована
    
    Serial.println("\n🚨 СИСТЕМА НЕ МОЖЕТ РАБОТАТЬ БЕЗ ДАТЧИКА ГИЛЬЗЫ!");
    Serial.println("   Возможные действия:");
    Serial.println("   1. Проверьте подключение датчика гильзы к GPIO4");
    Serial.println("   2. Введите команду FIND для принудительного поиска");
    Serial.println("   3. Используйте режим теста для проверки интерфейса");
  }
  
  // -------------------- ЭТАП 6: ФИНАЛЬНЫЙ ОТЧЁТ --------------------
  Serial.printf("\n📈 ИТОГОВАЯ СТАТИСТИКА: Найдено датчиков %d из 4\n", foundCount);
  Serial.println(String(60, '=') + "\n");
  
  // Возвращаем результат инициализации
  return systemInitialized;
}

