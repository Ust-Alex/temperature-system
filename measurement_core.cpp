/** * АВТОМАТИЧЕСКОЕ ВОССТАНОВЛЕНИЕ ПОТЕРЯННЫХ ДАТЧИКОВ
 * 
 * Назначение: Периодически пытаться восстановить связь с датчиками,
 *             которые были помечены как "потерянные" (found = false)
 *             Вызывается из задачи измерений по таймеру
 * 
 * Особенности:
 * - Работает даже при systemInitialized = false
 * - Может частично восстановить систему
 * - Подробное логирование процесса
 */
void attemptReconnect() {
  Serial.println(">>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>");
  Serial.println("🔄 АВТОМАТИЧЕСКОЕ ВОССТАНОВЛЕНИЕ ДАТЧИКОВ");
  Serial.println(" АВТОМАТИЧЕСКОЕ ВОССТАНОВЛЕНИЕ ДАТЧИКОВ");
  Serial.println(String(50, '-'));
  
  bool reconnectedAny = false;  // Флаг: удалось ли что-то восстановить
  
  // -------------------- ВОССТАНОВЛЕНИЕ ШИНЫ A (ГИЛЬЗА) --------------------
  // Проверяем только если датчик гильзы потерян
  if (!sensors[3].found) {
    Serial.println("🔍 Поиск датчика гильзы на шине A...");
    
    // ВАЖНО: Полная повторная инициализация шины
    oneWireA.begin(ONE_WIRE_BUS_A);      // Инициализация OneWire
    sensorsA.setOneWire(&oneWireA);      // Связывание с DallasTemperature
    sensorsA.begin();                    // Запуск библиотеки
    
    delay(200);  // Даём время на инициализацию
    
    // Проверяем наличие устройств
    int countA = sensorsA.getDeviceCount();
    
    if (countA > 0) {
      // Устройства найдены - пытаемся получить адрес
      DeviceAddress tempAddr;
      if (sensorsA.getAddress(tempAddr, 0)) {
        // ВОССТАНОВЛЕНИЕ УСПЕШНО!
        
        // Сохраняем адрес
        memcpy(sensors[3].addr, tempAddr, 8);
        
        // КРИТИЧЕСКИ ВАЖНО: Устанавливаем флаг "найден"
        sensors[3].found = true;
        
        // Настраиваем датчик
        sensorsA.setResolution(tempAddr, RESOLUTION);
        sensors[3].lostTimer = 0;  // Сбрасываем счётчик потерь
        
        Serial.println("   ✅ ДАТЧИК ГИЛЬЗЫ ВОССТАНОВЛЕН АВТОМАТИЧЕСКИ!");
        reconnectedAny = true;
        
        // Сбрасываем критическую ошибку ТОЛЬКО если восстановили гильзу
        criticalError = false;
      }
    } else {
      Serial.println("   ❌ На шине A устройства не обнаружены");
    }
  }
  
  // -------------------- ВОССТАНОВЛЕНИЕ ШИНЫ B (СТЕНКИ) --------------------
  // Всегда проверяем шину B, даже если некоторые датчики уже найдены
  Serial.println("🔍 Поиск датчиков стенки на шине B...");
  
  // Полная повторная инициализация шины B
  oneWireB.begin(ONE_WIRE_BUS_B);
  sensorsB.setOneWire(&oneWireB);
  sensorsB.begin();
  
  delay(200);
  
  int countB = sensorsB.getDeviceCount();
  
  if (countB > 0) {
    // Устройства найдены на шине B
    
    // Собираем все найденные адреса во временный массив
    DeviceAddress foundAddrs[3];
    int devicesToCheck = min(countB, 3);  // Максимум 3 датчика
    
    for (int i = 0; i < devicesToCheck; i++) {
      sensorsB.getAddress(foundAddrs[i], i);
    }
    
    // Пытаемся восстановить каждый потерянный датчик стенки
    for (int wallIdx = 0; wallIdx < 3; wallIdx++) {
      if (!sensors[wallIdx].found && devicesToCheck > 0) {
        // Простая схема привязки: циклическое распределение
        int addrIdx = (wallIdx + 1) % devicesToCheck;
        
        // Восстанавливаем датчик
        memcpy(sensors[wallIdx].addr, foundAddrs[addrIdx], 8);
        sensors[wallIdx].found = true;
        sensorsB.setResolution(foundAddrs[addrIdx], RESOLUTION);
        sensors[wallIdx].lostTimer = 0;
        
        Serial.printf("   ✅ %s восстановлен!\n", sensorNames[wallIdx]);
        reconnectedAny = true;
      }
    }
  } else {
    Serial.println("   ❌ На шине B устройства не обнаружены");
  }
  
  // -------------------- ИТОГИ ВОССТАНОВЛЕНИЯ --------------------
  Serial.println("------------------------------------------");
  Serial.println("📊 РЕЗУЛЬТАТЫ ВОССТАНОВЛЕНИЯ");
  
  if (reconnectedAny) {
    // Serial.println("✅ АВТОВОССТАНОВЛЕНИЕ ЗАВЕРШЕНО УСПЕШНО");
    
    // ДОПОЛНИТЕЛЬНАЯ ПРОВЕРКА: Если теперь есть гильза - система инициализирована
    if (sensors[3].found) {
      systemInitialized = true;
      criticalError = false;
      Serial.println("   📈 Система теперь инициализирована (гильза найдена)");
    }
    
    // Принудительно запрашиваем обновление дисплея
    forceDisplayRedraw = true;
    Serial.println("   🖥️  Дисплей будет обновлён");
  } else {
    Serial.println("❌ НЕ УДАЛОСЬ ВОССТАНОВИТЬ НИ ОДИН ДАТЧИК");
    Serial.println("   Проверьте физическое подключение датчиков");
  }
  
  Serial.println("<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<<");
}

