/** * БЕЗОПАСНОЕ ОБНОВЛЕНИЕ СИСТЕМНЫХ ДАННЫХ (с защитой мьютексом)
 * 
 * Назначение: Обновить температуры и дельты в общей структуре sysData
 *             с гарантией отсутствия гонки данных между задачами FreeRTOS
 * 
 * Параметры:
 *   idx   - индекс датчика (0-3)
 *   temp  - новое значение температуры
 *   delta - новое значение изменения температуры (ΔT)
 */
void safeUpdateSystemData(int idx, float temp, float delta) {
  // Пытаемся захватить мьютекс с таймаутом 10 мс
  if (xSemaphoreTake(dataMutex, pdMS_TO_TICKS(10)) == pdTRUE) {
    // Критическая секция: обновляем данные
    sysData.temps[idx] = temp;    // Сохраняем температуру
    sysData.deltas[idx] = delta;  // Сохраняем дельту
    
    // Освобождаем мьютекс для других задач
    xSemaphoreGive(dataMutex);
  }
  // Если мьютекс не удалось захватить - данные не обновляются
  // (лучше потерять одно измерение, чем заблокировать систему)
}

/** * БЕЗОПАСНОЕ ЧТЕНИЕ СИСТЕМНЫХ ДАННЫХ (с защитой мьютексом)
 * 
 * Назначение: Получить полную копию системных данных для передачи
 *             между задачами или для отладки
 * 
 * Параметры:
 *   data - указатель на структуру, куда будут скопированы данные
 */
void safeReadSystemData(SystemData_t* data) {
  // Захватываем мьютекс для безопасного доступа
  if (xSemaphoreTake(dataMutex, pdMS_TO_TICKS(10)) == pdTRUE) {
    // Копируем ВСЕ данные из sysData в предоставленную структуру
    memcpy(data, &sysData, sizeof(SystemData_t));
    
    // Освобождаем мьютекс
    xSemaphoreGive(dataMutex);
  }
}

