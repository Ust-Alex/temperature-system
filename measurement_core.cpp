/**
 * МЕДИАННЫЙ ФИЛЬТР ДЛЯ СГЛАЖИВАНИЯ ЗНАЧЕНИЙ ТЕМПЕРАТУРЫ
 * 
 * Назначение: Устранение случайных выбросов и помех в показаниях датчиков
 * Принцип работы: Использует кольцевой буфер из 5 последних значений
 *                 Возвращает скользящее среднее для стабильных показаний
 * 
 * Параметры:
 *   sensorIdx - индекс датчика (0-3)
 *   newValue  - новое сырое значение температуры
 * 
 * Возвращает: Отфильтрованное значение температуры
 */
float filterValue(int sensorIdx, float newValue) {
  // Защита от некорректных индексов
  if (sensorIdx < 0 || sensorIdx >= 4) return newValue;

  // Получаем указатель на структуру датчика для удобства доступа
  Sensor_t* s = &sensors[sensorIdx];

  // Статический массив флагов инициализации фильтров для каждого датчика
  static bool bufferInitialized[4] = { false, false, false, false };

  // ИНИЦИАЛИЗАЦИЯ ФИЛЬТРА (при первом вызове для датчика)
  if (!bufferInitialized[sensorIdx]) {
    // Заполняем весь буфер первым значением
    for (int j = 0; j < 5; j++) {
      s->filterBuffer[j] = newValue;
    }
    
    // Инициализируем сумму и индекс
    s->filterSum = newValue * 5.0f;  // Сумма 5 одинаковых значений
    s->filterIndex = 0;               // Начинаем с первого элемента буфера
    bufferInitialized[sensorIdx] = true;  // Помечаем фильтр как инициализированный
    
    return newValue;  // Возвращаем первое значение без фильтрации
  }

  // ОБНОВЛЕНИЕ ФИЛЬТРА (после инициализации)
  // 1. Удаляем самое старое значение из суммы
  s->filterSum -= s->filterBuffer[s->filterIndex];
  
  // 2. Заменяем старое значение на новое в буфере
  s->filterBuffer[s->filterIndex] = newValue;
  
  // 3. Добавляем новое значение к сумме
  s->filterSum += newValue;
  
  // 4. Перемещаем индекс к следующему элементу (кольцевой буфер)
  s->filterIndex = (s->filterIndex + 1) % 5;

  // 5. Возвращаем среднее значение (скользящее среднее)
  return s->filterSum / 5.0f;
}

/** * ПРОВЕРКА ВАЛИДНОСТИ ЗНАЧЕНИЯ ТЕМПЕРАТУРЫ
 * 
 * Назначение: Отфильтровать некорректные значения от датчиков
 *             (ошибки чтения, физически невозможные температуры)
 * 
 * Параметры:
 *   temp - проверяемое значение температуры
 * 
 * Возвращает: true если температура валидна, false если это ошибка
 */
bool isValidTemperature(float temp) {
  // Проверяем все возможные некорректные состояния:
  return !(temp == TEMP_NO_DATA ||         // Нет данных (инициализация)
           temp == TEMP_SENSOR_LOST ||     // Датчик стенки потерян
           temp == TEMP_CRITICAL_LOST ||   // Датчик гильзы потерян (критично!)
           temp == -999.0f ||              // Специальное значение ошибки
           temp < -50.0f ||                // Физически невозможная низкая температура
           temp > 150.0f);                 // Физически невозможная высокая температура
}

