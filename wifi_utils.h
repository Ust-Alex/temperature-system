/**
 * ============================================================================
 * @file wifi_utils.h
 * @brief ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ ДЛЯ РАБОТЫ С Wi-Fi
 * @version 6.2
 * 
 * Содержит:
 * - Получение реальной мощности передатчика
 * - Формирование JSON с данными температур
 * - Отправка данных и звуковых команд клиентам
 * ============================================================================
 */

#ifndef WIFI_UTILS_H
#define WIFI_UTILS_H

#include <Arduino.h>

// ============================================================================
// ПОЛУЧЕНИЕ РЕАЛЬНОЙ МОЩНОСТИ ПЕРЕДАТЧИКА
// ============================================================================
/**
 * @brief Получает реальную мощность Wi-Fi из чипа ESP32
 * @return Мощность в дБм (например, 18), или -1 при ошибке
 */
int8_t getRealTxPower();

// ============================================================================
// ОТПРАВКА ДАННЫХ КЛИЕНТАМ
// ============================================================================
/**
 * @brief Формирует JSON с температурами и отправляет всем клиентам
 */
void sendTemperaturesToClients();

/**
 * @brief Отправляет JSON-сообщение всем клиентам через WebSocket
 * @param json Указатель на строку JSON
 */
void broadcastJSON(const char* json);

/**
 * @brief Отправляет звуковую команду всем клиентам
 * @param soundType Тип звука (например, "zhdati", "ready")
 */
void sendSoundCommand(const char* soundType);

#endif // WIFI_UTILS_H