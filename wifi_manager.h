/**
 * ============================================================================
 * @file wifi_manager.h
 * @brief УПРАВЛЕНИЕ ПОДКЛЮЧЕНИЕМ К Wi-Fi
 * @version 6.2
 * 
 * Основные функции:
 * - connectSTA()  – подключение к роутеру (перебор двух сетей)
 * - reconnectSTA() – переподключение при потере связи
 * - startAP()     – запуск режима точки доступа
 * ============================================================================
 */

#ifndef WIFI_MANAGER_H
#define WIFI_MANAGER_H

#include <Arduino.h>

// ============================================================================
// ГЛОБАЛЬНЫЕ ПЕРЕМЕННЫЕ (объявления)
// ============================================================================
extern bool wifiModeAP;
extern String lastConnectedSSID;

// ============================================================================
// ОСНОВНЫЕ ФУНКЦИИ
// ============================================================================

/**
 * @brief Подключение к роутеру с перебором двух сетей
 * @return true – подключено успешно, false – не удалось
 */
bool connectSTA();

/**
 * @brief Переподключение при потере связи
 * @return true – связь восстановлена, false – не удалось
 */
bool reconnectSTA();

/**
 * @brief Запуск режима точки доступа (AP)
 */
void startAP();

#endif // WIFI_MANAGER_H