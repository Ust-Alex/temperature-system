#ifndef SENSORS_H
#define SENSORS_H

#include <Arduino.h>
#include <OneWire.h>
#include <DallasTemperature.h>

// ============================================================================
// ИНИЦИАЛИЗАЦИЯ МОДУЛЯ
// ============================================================================
void sensors_init();                    // Начальная инициализация датчиков
void sensors_scan_all();                 // Поиск всех датчиков на шинах

// ============================================================================
// ОПРОС ДАТЧИКОВ
// ============================================================================
void sensors_request_temperatures();    // Запрос на преобразование (асинхронный)
void sensors_read_temperatures();       // Чтение результатов
void sensors_update_all();               // Полный цикл: запрос + чтение + фильтрация

// ============================================================================
// ДОСТУП К ДАННЫМ
// ============================================================================
float sensors_get_temp(int idx);        // Получить температуру датчика
bool sensors_is_found(int idx);          // Проверить, найден ли датчик
float sensors_get_filtered(int idx);    // Получить отфильтрованное значение

// ============================================================================
// ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
// ============================================================================
bool sensors_is_valid(float temp);       // Проверить валидность температуры
void sensors_print_address(int idx);     // Вывести адрес датчика в Serial

#endif