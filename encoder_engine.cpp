#include "encoder_engine.h"
#include "system_config.h"
#include <EncButton.h>

// ============================================================================
// ЛОКАЛЬНЫЕ ПЕРЕМЕННЫЕ (STATIC - ВИДНЫ ТОЛЬКО В ЭТОМ ФАЙЛЕ)
// ============================================================================

// Объект энкодера из библиотеки EncButton
// Параметры: CLK, DT, SW, режим пинов (INPUT_PULLUP)
static EncButton enc(ENCODER_CLK, ENCODER_DT, ENCODER_SW, INPUT_PULLUP);

// Время последней активности пользователя (для таймаута)
static uint32_t lastActivityTime = 0;

// Флаг для отслеживания состояния удержания
static bool holdActive = false;

// ============================================================================
// ИНИЦИАЛИЗАЦИЯ ЭНКОДЕРА
// ============================================================================
void encoder_init() {
    Serial.println("[ENCODER] Инициализация энкодера...");
    
    // НАСТРОЙКА УРОВНЯ СИГНАЛА КНОПКИ
    // LOW - кнопка замыкает на GND (активный низкий уровень)
    enc.setBtnLevel(LOW);
    
    // НАСТРОЙКА ТАЙМАУТОВ (в миллисекундах)
    enc.setClickTimeout(500);   // Макс. время между кликами для двойного нажатия
    enc.setDebTimeout(50);      // Время гашения дребезга контактов
    enc.setHoldTimeout(400);    // Время до срабатывания удержания (400 мс)
    enc.setStepTimeout(200);    // Период импульсов при удержании (200 мс)
    enc.setTimeout(1000);       // Общий таймаут действия
    
    // НАСТРОЙКА ЭНКОДЕРА (декодера)
    enc.setEncReverse(0);       // 0 - нормальное направление, 1 - реверс
    enc.setEncType(EB_STEP4_LOW); // Тип сигнала: 4 фазы за щелчок, активный LOW
    enc.setFastTimeout(30);     // Таймаут быстрого поворота
    
    // Сброс счётчика энкодера
    enc.counter = 0;
    
    // Сброс флагов состояния
    holdActive = false;
    
    // Инициализация таймера неактивности
    lastActivityTime = millis();
    
    Serial.println("[ENCODER] Энкодер инициализирован");
    Serial.printf("[ENCODER] Пины: CLK=%d, DT=%d, SW=%d\n", 
                  ENCODER_CLK, ENCODER_DT, ENCODER_SW);
    Serial.printf("[ENCODER] Таймаут удержания: 400 мс\n");
}

// ============================================================================
// ОПРОС ЭНКОДЕРА - ВЫЗЫВАТЬ КАЖДЫЕ 10-20 МС
// ============================================================================
EncoderEvent_t encoder_tick() {
    // Опрос библиотеки EncButton (обязательно вызывать часто)
    enc.tick();
    
    // ========================================================================
    // ШАГ 1: СБРОС ТАЙМЕРА НЕАКТИВНОСТИ ПРИ ЛЮБОМ ДЕЙСТВИИ
    // ========================================================================
    if (enc.action()) {
        lastActivityTime = millis();
    }
    
    // ========================================================================
    // ШАГ 2: ОБРАБОТКА УДЕРЖАНИЯ + ПОВОРОТА (НАИВЫСШИЙ ПРИОРИТЕТ)
    // ========================================================================
    // Если кнопка удерживается, обрабатываем повороты специальным образом
    if (enc.hold()) {
        // Если удержание только что началось - устанавливаем флаг
        if (!holdActive) {
            holdActive = true;
            // Можно вернуть EVENT_BUTTON_HOLD, если нужно отдельное событие начала удержания
            // return EVENT_BUTTON_HOLD;
        }
        
        // Проверяем повороты во время удержания
        if (enc.left()) {
            return EVENT_HOLD_LEFT;   // Поворот влево с удержанием
        } else if (enc.right()) {
            return EVENT_HOLD_RIGHT;  // Поворот вправо с удержанием
        }
    } else {
        // Если кнопка не удерживается, сбрасываем флаг
        holdActive = false;
    }
    
    // ========================================================================
    // ШАГ 3: ОБЫЧНЫЙ ПОВОРОТ (БЕЗ УДЕРЖАНИЯ)
    // ========================================================================
    if (enc.turn()) {
        if (enc.left()) {
            return EVENT_ENCODER_LEFT;
        } else if (enc.right()) {
            return EVENT_ENCODER_RIGHT;
        }
    }
    
    // ========================================================================
    // ШАГ 4: СОБЫТИЯ КНОПКИ (БЕЗ ПОВОРОТА)
    // ========================================================================
    if (enc.click()) {
        if (enc.hasClicks(2)) {
            return EVENT_BUTTON_DOUBLE;  // Двойное нажатие
        } else {
            return EVENT_BUTTON_CLICK;    // Одиночный клик
        }
    }
    
    // ========================================================================
    // ШАГ 5: НАЧАЛО УДЕРЖАНИЯ (ОТДЕЛЬНОЕ СОБЫТИЕ, ЕСЛИ НУЖНО)
    // ========================================================================
    // Раскомментируйте, если нужно получать событие именно в момент начала удержания
    // if (enc.hold() && !holdActive) {
    //     holdActive = true;
    //     return EVENT_BUTTON_HOLD;
    // }
    
    // ========================================================================
    // ШАГ 6: НИЧЕГО НЕ ПРОИЗОШЛО
    // ========================================================================
    return EVENT_NONE;
}

// ============================================================================
// СБРОС ТАЙМЕРА НЕАКТИВНОСТИ
// ============================================================================
void encoder_reset_inactivity_timer() {
    lastActivityTime = millis();
}

// ============================================================================
// ПОЛУЧЕНИЕ ВРЕМЕНИ НЕАКТИВНОСТИ (В МИЛЛИСЕКУНДАХ)
// ============================================================================
uint32_t encoder_get_inactivity_time() {
    return millis() - lastActivityTime;
}