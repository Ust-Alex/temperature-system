#ifndef MENU_ENGINE_H
#define MENU_ENGINE_H

#include <Arduino.h>
#include "encoder_engine.h"  // Для типов событий

// ============================================================================
// СОСТОЯНИЯ МЕНЮ
// ============================================================================
typedef enum {
    MENU_STATE_MAIN = 0,        // Главный экран (температуры)
    MENU_STATE_TOP, 
    MENU_STATE_MODE_SELECT,     // Выбор режима (MODE1/MODE2)
    MENU_STATE_CALIB,           // Калибровка датчиков
    MENU_STATE_STATUS,          // Информация о статусе
    MENU_STATE_SETTINGS,        // Настройки системы
    MENU_STATE_MP3_VOL,         // Регулировка громкости MP3
    MENU_STATE_WIFI,            // WiFi (для будущего)
    MENU_STATE_COUNT            // Количество состояний (для цикличности)
} MenuState_t;

// ============================================================================
// ИНИЦИАЛИЗАЦИЯ МОДУЛЯ
// ============================================================================
void menu_init();

// ============================================================================
// ОБРАБОТКА СОБЫТИЙ ЭНКОДЕРА (ВЫЗЫВАТЬ ИЗ TASKDISPLAY)
// ============================================================================
void menu_handle_event(EncoderEvent_t event);

void menu_check_timeout();  // Проверка таймаута (вызывать из taskDisplay)

// ============================================================================
// ПОЛУЧЕНИЕ ТЕКУЩЕГО СОСТОЯНИЯ
// ============================================================================
MenuState_t menu_get_current_state();
bool menu_is_active();  // true если не в MAIN

#endif // MENU_ENGINE_H