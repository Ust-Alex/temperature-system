/**
 * @file menu_engine.h
 * @brief ЗАГОЛОВОЧНЫЙ ФАЙЛ МОДУЛЯ УПРАВЛЕНИЯ МЕНЮ
 * 
 * @version 1.0
 * @date 2026
 * 
 * @details Определяет публичный интерфейс для работы с меню через энкодер.
 *          Другие модули (например, задача дисплея) используют эти функции
 *          для передачи событий энкодера и проверки состояния меню.
 * 
 * @note Этот файл остаётся неизменным при разделении реализации на логику и графику.
 */

#ifndef MENU_ENGINE_H
#define MENU_ENGINE_H

#include <Arduino.h>
#include "encoder_engine.h"  // Для использования типа EncoderEvent_t

// ============================================================================
// ПЕРЕЧИСЛЕНИЕ СОСТОЯНИЙ МЕНЮ
// ============================================================================
/**
 * @enum MenuState_t
 * @brief Возможные состояния (экраны) меню.
 * 
 * Используется для определения текущего режима отображения и навигации.
 * Значения упорядочены для возможной цикличности, но не все состояния
 * могут быть реализованы в текущей версии.
 */
typedef enum {
    MENU_STATE_MAIN = 0,        /**< Главный экран (отображение температур по умолчанию) */
    MENU_STATE_TOP,             /**< Верхнее меню (MODE, VOLUME, CALIB, SETTINGS) */
    MENU_STATE_MODE_SELECT,     /**< Экран выбора режима работы (MODE1/MODE2) */
    MENU_STATE_CALIB,           /**< Экран калибровки датчиков */
    MENU_STATE_STATUS,          /**< Информация о статусе системы */
    MENU_STATE_SETTINGS,        /**< Общие настройки системы */
    MENU_STATE_MP3_VOL,         /**< Экран регулировки громкости MP3 */
    MENU_STATE_WIFI,            /**< Настройки WiFi (зарезервировано для будущего) */
    MENU_STATE_COUNT            /**< Количество состояний (для проверок и циклов) */
} MenuState_t;

// ============================================================================
// ФУНКЦИИ ИНИЦИАЛИЗАЦИИ И УПРАВЛЕНИЯ
// ============================================================================

/**
 * @brief Инициализирует модуль меню.
 * 
 * Устанавливает начальное состояние (MENU_STATE_MAIN), сбрасывает переменные
 * навигации и внутренний кэш графики. Должна вызываться один раз при старте системы.
 */
void menu_init();

/**
 * @brief Обрабатывает событие от энкодера.
 * 
 * Это основная функция логики меню. Она получает событие (поворот, нажатие, удержание)
 * и в зависимости от текущего состояния меню изменяет внутренние переменные
 * (выбранный пункт, режим и т.д.) и вызывает соответствующие функции отрисовки.
 * 
 * @param event Событие энкодера (тип EncoderEvent_t из encoder_engine.h).
 * @note Должна вызываться из задачи дисплея при появлении события в очереди.
 */
void menu_handle_event(EncoderEvent_t event);

/**
 * @brief Проверяет таймаут неактивности меню.
 * 
 * Если меню активно (не в состоянии MAIN) и прошло больше MENU_INACTIVITY_TIMEOUT
 * миллисекунд с последнего действия, функция переводит меню в состояние MAIN
 * и запрашивает полную перерисовку главного экрана.
 * 
 * @note Должна вызываться регулярно из цикла задачи дисплея.
 */
void menu_check_timeout();

// ============================================================================
// ФУНКЦИИ ПОЛУЧЕНИЯ СОСТОЯНИЯ
// ============================================================================

/**
 * @brief Возвращает текущее состояние меню.
 * @return MenuState_t Текущее состояние.
 */
MenuState_t menu_get_current_state();

/**
 * @brief Проверяет, активно ли меню.
 * @return true если меню не в состоянии MAIN (т.е. открыто), иначе false.
 */
bool menu_is_active();

#endif // MENU_ENGINE_H